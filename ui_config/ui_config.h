#ifndef __UI_CONFIG_H__
#define __UI_CONFIG_H__

#include <stdint.h>     /* 下面有的宏用到 int32_t */

/* ==================================================================
 *  UI 库的可调参数 —— 全部集中在这里，按模块分类
 *
 *  这里只放"能调的数"和"开关"：尺寸、容量、上限、阈值。
 *  不放接口契约（结构体定义、回调签名）和位标志 —— 那些跟着各自模块走。
 *
 *  有几条直接决定 RAM 占用和每帧耗时，改之前先看该条的说明。
 *  各模块自己的 .h/.c 里只留一句"参数在 ui_config.h"，不再重复定义。
 * ================================================================== */


/* ==================================================================
 *  一、屏幕尺寸 —— ui_dirty_areas
 *
 *  行缓冲和脏矩形表都按它算，所以放在最前面。
 *  实际屏幕比它小的时候，开机时用 ui_dirty_set_screen() 告诉脏区模块；
 *  不设就会把屏外坐标当成脏区收进来。
 * ================================================================== */
#define MAX_W   1024
#define MAX_H   600


/* ==================================================================
 *  二、行缓冲 —— ui_dirty_areas
 * ================================================================== */

/* 一块行缓冲最多装多少像素：脏矩形按"整宽 × 尽量多行"切片推，切到不超过它为止。
 * 取 20 行整屏宽，和以前那套条带的容量一样。
 * 这是本模块 RAM 占用的大头 —— 两块这样的缓冲 */
#define BUF_PIXELS   (20 * MAX_W)


/* ==================================================================
 *  三、脏矩形表 —— ui_dirty_areas
 * ================================================================== */

/* UI_DIRTY_MAX_CAP：表静态能装多少块（每块 8 字节，64 → 512 字节 RAM）。
 * UI_DIRTY_MAX_MIN：运行时可设置的下限。
 * 实际容量由 ui_dirty_set_max 设定，不设就用满 CAP。
 * 用量估算：只描边的对象（光标 / 矩形）约 3~4 块，整体标记的对象（文本 / 圆 / 折线）1~2 块；
 * 容量越大越能"一处脏一块"，越小则每帧的扫描 / 合并越快，但越早触发下面的退化 */
#define UI_DIRTY_MAX_CAP   64
#define UI_DIRTY_MAX_MIN    8

/* 表满时，"并进最合适的那一块"如果要多推超过这个像素数，就不再并、直接整屏标脏。
 * 取约半屏：超过它时那一帧本来就慢得差不多了，不如退化成"形状可预测"的整屏重画 */
#define DIRTY_OVERFLOW_COST_MAX  ((int32_t)MAX_W * (int32_t)MAX_H / 2)

/* ---- 双缓冲要补的"上一帧脏区" ----
 * 双缓冲下后台缓冲欠的是"自它上次显示以来"的所有变化 = 上一帧的脏区 ∪ 这一帧的脏区，
 * 所以得把上一帧的脏矩形存下来，下一帧一开标脏就先把它们补进脏矩形表。
 * UI_DIRTY_KEEP_PREV：总开关。改成 0 就退回单缓冲行为，一个像素都不多推。
 * UI_DIRTY_PREV_MAX ：上一帧最多记几块（多的两两合并）；以后三缓冲再扩 */
#define UI_DIRTY_KEEP_PREV   1
#define UI_DIRTY_PREV_MAX    3

/* 标脏裁剪栈的深度：ui_dirty_clip_push 可嵌套，超过后只夹不存 */
#define UI_DIRTY_CLIP_MAX  4


/* ==================================================================
 *  四、绘制裁剪 —— ui_dirty_areas
 * ================================================================== */

/* 绘制裁剪栈的深度：ui_row_clip_push 可嵌套，超过后只夹不存。
 * 正常嵌套一两层用不到这个上限 */
#define UI_ROW_CLIP_MAX  8


/* ==================================================================
 *  五、文本 —— ui_create
 * ================================================================== */

/* 一个文本框一次最多排几行（'\n' 强制换行 + 自动折行一起算）。
 * 超出就截断，所以给够；每行占 6 字节栈上空间 */
#define UI_TEXT_MAX_LINES  24


/* ==================================================================
 *  六、字库 —— ui_font / APP/ui_font_port
 * ================================================================== */

/* 一个字模最多占多少字节：1bpp 48×48 = 288 B；
 * 灰度字库(8bit alpha)最大一档 48×48 = 2304 B —— 取两者的大者。
 * ui_draw_text 按它准备取模缓冲，读点阵的函数往缓冲里写的量不能超过这个数 */
#define UI_GLYPH_MAX_BYTES  2304u

/* 字模缓存的槽数，必须是 2 的幂（内部用 & (N-1) 取模）。
 * 每槽 = 8 字节头 + UI_GLYPH_MAX_BYTES，32 槽约 74KB RAM(AXI SRAM)。
 * 界面上真正用到的字通常就几十个，加大只是少读几次介质，代价是 RAM；
 * 灰度字库每字更大(24×24=576B / 32×32=1024B / 48×48=2304B)，槽数按 RAM 余量调 */
#define UI_FONT_CACHE_NUM   32u


/* ==================================================================
 *  六·五、图片 / 图标 —— ui_create / ui_tool
 * ================================================================== */

/* 片外图标取行的落地缓冲容量（像素；栈上 2 字节/像素）。
 * ui_draw_image 用它从取行回调分批读像素：规格比它宽的图片会自动分段读，
 * 不会画错，只是每行多调几次回调 —— 常用图标规格(32/64)一段就读完 */
#define UI_IMG_ROW_BUF_PIX  128u


/* ==================================================================
 *  七、事件 —— ui_event
 * ================================================================== */

/* 事件层最多同时跟踪几个触点。必须 >= 触摸驱动一次能报的最大点数
 * (Drivers/BSP/TOUCH 的 CT_MAX_TOUCH = 10)，否则多出来的点会被丢掉。
 * 每个触点占 (2 个对象指针 + 2 个坐标 + 1 个标志) ≈ 13 字节 RAM */
#define UI_EVENT_TOUCH_MAX  10u

/* 事件层调试打印：1 = 每产生一个事件就往串口打一行(type + 坐标 + 位移)。
 * 默认关 —— 库平时不该往串口吐东西；调试"事件有没有派发出来"时再打开 */
#define UI_EVENT_DEBUG      0

/* ==================================================================
 *  八、命中测试 —— ui_control
 * ================================================================== */

/* 最小可点尺寸(px)：命中框不足这个边长的，向四周补齐到它；本来就够大的对象不受影响。
 * 触摸屏上 32×32 的小图标拿外框直接做命中太难点，44 是常用的手指目标尺寸
 * (32×32 每边补 6 -> 44×44)。设 0 = 关掉补齐，回到"严格按外框命中" */
#define UI_HIT_MIN_SIZE     64

/* 命中区调试框：1 = 每一帧在每个【可点对象】的命中框上描一圈(含上面 UI_HIT_MIN_SIZE 的补齐)。
 * 用来目视核对"到底哪里能点到"；只是多画几圈线，不影响命中逻辑。
 * 正式固件改回 0 即可(调用处见 User/main.c 的 app_draw_level) */
#define UI_HIT_DEBUG_DRAW   0


/* ---- 调试 HUD(帧率 / 触点坐标) ----------------------------------------
 * 1 = 屏幕右上角常驻一块半透明信息板：帧率 + 最近触点坐标(按下 / 松开)。
 * 【不是 UI 对象】：它挂在推屏流水线的浮层钩子上，每片场景画完、交给硬件前直接写进行缓冲，所以
 *   · 永远压在所有页面之上；
 *   · 不参与命中测试 —— 点击 / 拖动全部穿透到下面的对象，点不中也选不中；
 *   · 不进任何链 / 层级，不占脏区表容量。
 * 只在内容变化(帧率每秒更新、坐标变化)时标脏，静态时几乎不产生额外重绘。
 * 实现在 ui_module.c：首次 ui_module_task_all() 时自动挂到推屏流水线的浮层钩子上，
 * 应用侧不用写任何代码；正式固件改回 0 即可 */
#define UI_DEBUG_HUD        0

/* HUD 外观(只有 UI_DEBUG_HUD = 1 时才用)：尺寸 / 离屏幕上右两边的距离 / 透明度 */
#define UI_DEBUG_HUD_W       168
#define UI_DEBUG_HUD_H       46
#define UI_DEBUG_HUD_MARGIN  8      /* 距屏幕上边、右边的像素 */
#define UI_DEBUG_HUD_BG_A    140    /* 底色不透明度：0/255 不透明，1~254 半透明 */
#define UI_DEBUG_HUD_TXT_A   230    /* 文字不透明度 */


/* ==================================================================
 *  九、每帧任务 —— ui_module
 * ================================================================== */

/* 每帧任务注册表最多登记多少个任务(组件任务 + 页面任务一起算)。
 * 每槽 12 字节 RAM：12 槽 144 B、32 槽 384 B、64 槽 768 B。
 * 注册只在开机装配时发生(线性找槽，几十次比较可以忽略)；
 * 每帧按槽扫一遍，32 / 64 个空槽的两次比较对 M7 的帧耗时没有可测影响。
 * 超了 ui_module_task_register* 返回 0，不会静默丢任务 */
#define UI_MODULE_TASK_MAX  32u



/* ==================================================================
 *  十、颜色格式 ?? 配色宏
 *
 *  颜色一律用 UI_RGB(r, g, b) 写，r/g/b 取 0~255；用 UI_COLOR_FMT 选打包格式。
 *
 *  库内部所有"颜色 / 像素"都用 ui_color_t：16bit 档是 uint16_t，32bit 档是 uint32_t。
 *  行缓冲、图片像素、键色、各图元的 color 字段全部跟着它走，库内不再出现写死的 565 位运算。
 *
 *  移植到别的像素格式：改 UI_COLOR_FMT，再在【外部】适配这些（不属于库）：
 *    ? LTDC：像素格式 / 帧缓存大小 / 行偏移 / DMA2D 目标格式
 *    ? 片外图标/图片：按新格式重新转换（当前工具输出 RGB565 小端）
 *  库内混色 / 渐变统一走 ui_color_blend() 和 ui_color_lerp()（见 ui_dirty_areas）
 * ================================================================== */
#define UI_COLOR_FMT_RGB565     0     /* 16bit R5 G6 B5(默认) */
#define UI_COLOR_FMT_BGR565     1     /* 16bit B5 G6 R5(R/B 交换) */
#define UI_COLOR_FMT_RGB888     2     /* 32bit 容器装 R8 G8 B8 */
#define UI_COLOR_FMT_ARGB8888   3     /* 32bit A8 R8 G8 B8 */

/* ---- 当前使用的配色格式：只改这里 ---- */
#define UI_COLOR_FMT            UI_COLOR_FMT_RGB565

/* ---- 各格式打包宏 ---- */
#define UI_RGB565(r, g, b)      ((uint16_t)((((r) & 0xF8u) << 8) | (((g) & 0xFCu) << 3) | (((b) & 0xF8u) >> 3)))
#define UI_BGR565(r, g, b)      ((uint16_t)((((b) & 0xF8u) << 8) | (((g) & 0xFCu) << 3) | (((r) & 0xF8u) >> 3)))
#define UI_RGB888(r, g, b)      ((uint32_t)((((uint32_t)(r) & 0xFFu) << 16) | (((uint32_t)(g) & 0xFFu) << 8) | ((uint32_t)(b) & 0xFFu)))
#define UI_ARGB8888(a, r, g, b) ((uint32_t)((((uint32_t)(a) & 0xFFu) << 24) | (((uint32_t)(r) & 0xFFu) << 16) | (((uint32_t)(g) & 0xFFu) << 8) | ((uint32_t)(b) & 0xFFu)))

/* ---- 统一入口：UI_RGB() 跟着 UI_COLOR_FMT 走 ---- */
#if   (UI_COLOR_FMT == UI_COLOR_FMT_RGB565)
#define UI_RGB(r, g, b)         UI_RGB565(r, g, b)
#elif (UI_COLOR_FMT == UI_COLOR_FMT_BGR565)
#define UI_RGB(r, g, b)         UI_BGR565(r, g, b)
#elif (UI_COLOR_FMT == UI_COLOR_FMT_RGB888)
#define UI_RGB(r, g, b)         UI_RGB888(r, g, b)
#elif (UI_COLOR_FMT == UI_COLOR_FMT_ARGB8888)
#define UI_RGB(r, g, b)         UI_ARGB8888(255u, r, g, b)
#else
#error "UI_COLOR_FMT 取值无效，见 ui_config.h 第十节"
#endif

/* ---- 颜色 / 像素 的存储类型：库内统一用它 ---- */
#if (UI_COLOR_FMT == UI_COLOR_FMT_RGB565) || (UI_COLOR_FMT == UI_COLOR_FMT_BGR565)
typedef uint16_t ui_color_t;
#define UI_PIXEL_BYTES  2u      /* 一个像素占几个字节(外部适配帧缓存/行偏移时用) */
#elif (UI_COLOR_FMT == UI_COLOR_FMT_RGB888) || (UI_COLOR_FMT == UI_COLOR_FMT_ARGB8888)
typedef uint32_t ui_color_t;
#define UI_PIXEL_BYTES  4u
#else
#error "UI_COLOR_FMT 取值无效，见 ui_config.h 第十节"
#endif
#endif
