/**
 ****************************************************************************************************
 * @file        ui_event.h
 * @brief       UI 事件层 —— 把触摸变成对象能收到的事件
 * @note        事件类型(UI_EV_*)、事件结构(ui_event_t)、回调签名(ui_cb_t) 都在 ui_framework.h
 *              里定义；本模块是**产生**它们的地方：命中测试 + 触点状态机 + 派发。
 *
 *              库不碰 BSP：应用侧读完触摸驱动、把坐标换算成屏幕坐标，再喂进 ui_event_feed() ——
 *              和字库那层"库只认一个读点阵函数"是同一个思路。
 *              板级适配(驱动 / 屏的安装方向)在 APP/ui_touch_port/。
 ****************************************************************************************************
 */

#ifndef __UI_EVENT_H__
#define __UI_EVENT_H__

#include <stdint.h>

#include "./ui_framework/ui_framework.h"   /* ui_hierarchy_t / ui_event_t / ui_cb_t / UI_EV_* */


/* 一个触点。
 * id 是【跨帧认同一个手指】的身份，要填驱动给的跟踪号，不是数组下标 ——
 * 驱动是"前面 n 个槽有效"这样报点的，手指抬起时后面的点会被顶到 x[0]，
 * 光靠下标认不住同一个手指，于是就不知道"是哪个手指抬了"，点击永远合成不出来。
 * id 必须 < UI_EVENT_TOUCH_MAX(在 ui_config.h)，超出的点会被丢掉。 */
typedef struct
{
  uint8_t id;
  int16_t x;        /* 屏幕坐标 —— 应用侧负责把驱动坐标换算过来 */
  int16_t y;
}ui_touch_point_t;


/* 事件派发到哪个层级 —— 切页时改。没注册过的话 ui_event_feed 什么都不做 */
void ui_event_set_level(ui_hierarchy_t* level);

/* 喂进"这一帧的全部触点"。应用侧每帧调一次(和渲染同频)。
 *
 * @param pts     : 触点数组；坐标必须是【屏幕坐标】
 * @param count   : 触点个数；0 = 手指全抬起了
 * @param time_ms : 这一帧的时刻(ms)，会填进 ui_event_t::time_ms
 *                  (长按 / 双击 / 滑动速度以后要用它)
 * @retval        无
 *
 * 为什么收"一组触点"而不是"一个坐标 + 个数"：
 *   多触点的坐标本来就有一组；而且"同一时刻有几个手指、分别在哪"必须一次拿到 ——
 *   以后做双指缩放 / 旋转要靠它，分成多次调用就拼不出同一时刻的全貌。
 *
 * 每个触点各走一套状态机，合成出来的事件按顺序是：
 *   DOWN   —— 按下那一刻命中的对象(点在空白处就没人收到)
 *   MOVE   —— 发给【按下时那个对象】，即使手指已经移出它的框(拖拽要靠它持续跟手)；
 *             坐标没变就不发，省掉一堆没意义的回调
 *   UP     —— 手指松了
 *   CLICK  —— 紧跟在 UP 后面：只有"松手时还落在按下那个对象上"才补这一个
 *   CANCEL —— 移出去之后才松手：不发 UP / CLICK，改发这个
 *             (处理函数在 DOWN 里改过的外观，正好在这里恢复)
 *
 * 处理函数通常只看 CLICK 就够；只关心 UP 的处理函数不用管 CLICK，它会自然忽略。
 * 回调的返回值(1 = 已处理)现在还没用到，是留给以后做事件传递的。 */
void ui_event_feed(const ui_touch_point_t* pts, uint8_t count, uint32_t time_ms);

/* 最近一次喂进来的触点状态（调试 HUD / 日志用，不影响事件派发）：
 *   返回 1 = 现在有手指按着；0 = 全抬起了（或还没喂过）。
 *   x / y 输出最近一次的屏幕坐标（全部抬起后保留最后位置）；三个参数都可以传 NULL */
uint8_t ui_event_last_touch(int16_t *x, int16_t *y, uint8_t *down);


#endif
